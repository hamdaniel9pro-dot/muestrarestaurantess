window.translations = translations;

function applyTranslations(lang) {
  document.documentElement.setAttribute("lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const entry = translations[key];
    if (entry && entry[lang]) {
      el.textContent = entry[lang];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const entry = translations[key];
    if (entry && entry[lang]) {
      el.setAttribute("placeholder", entry[lang]);
    }
  });

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
  });

  try {
    localStorage.setItem("altura_lang", lang);
  } catch (e) { /* almacenamiento no disponible */ }

  document.dispatchEvent(new CustomEvent("altura:langchange", { detail: { lang } }));
}

function initLanguageSwitch() {
  const buttons = document.querySelectorAll(".lang-btn");
  let savedLang = "es";
  try {
    const stored = localStorage.getItem("altura_lang");
    if (stored === "es" || stored === "en") savedLang = stored;
  } catch (e) {
    savedLang = "es";
  }

  applyTranslations(savedLang);

  buttons.forEach((btn) => {
    btn.addEventListener("click", () => {
      const lang = btn.getAttribute("data-lang");
      applyTranslations(lang);
    });
  });
}

document.addEventListener("DOMContentLoaded", initLanguageSwitch);
